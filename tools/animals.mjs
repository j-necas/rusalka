// Animals for the app from an approved set (navrhy/zviratka-…/finalni-sada-vN, manifest.json):
//   static/animals/<id>.webp   2×2 atlas of expressions (idle, blink / happy, wink), 288 px cell (140 px on retina)
//   static/animals/motion.js    blink and joy timing and the CSS motion curves (sets v1/v2 – the motion without WebGL)
//   static/animals/v13/         the original drawing (<id>.webp) and the clean plate under the eyes (<id>-oci.webp)
//   static/animals/v13.js       rig for static/lib/natural.js (set V13: eyes, mouth, head anchor, paws, soft parts)
// node tools/animals.mjs <set folder>   (atlases need ImageMagick `magick` and `cwebp`)
// A V13 set (rig-data.json with clean plates) leaves motion.js as it is: the sets from v7 on carry no CSS motion.
import { readFileSync, writeFileSync, mkdirSync, rmSync, existsSync } from 'node:fs';
import { execFileSync } from 'node:child_process';
import { join } from 'node:path';
import vm from 'node:vm';
import { tmpdir } from 'node:os';
import { fileURLToPath } from 'node:url';

const K = fileURLToPath(new URL('../', import.meta.url));
const CIL = join(K, 'static/animals');
const HLAVICKA = '// Generated by tools/animals.mjs from the animal set – do not edit by hand.\n';
/** 576 px atlas (288 px cell) of one animal from the set's sprite */
function atlas(sada, z) {
  const tmp = join(tmpdir(), 'rusalka-animals.png');
  execFileSync('magick', [join(sada, z.sprite), '-filter', 'Lanczos', '-resize', '576x576', tmp]);
  execFileSync('cwebp', ['-quiet', '-q', '88', '-alpha_q', '100', '-exact', tmp, '-o', join(CIL, `${z.id}.webp`)]);
  rmSync(tmp, { force: true });
}

function atlasy(sada, m) {
  if (m.spriteGrid?.frameOrder?.join() !== 'idle,blink,happy,wink') throw new Error('unexpected order of expressions in the atlas');
  const pohyb = {};
  for (const z of m.animals) {
    atlas(sada, z);
    const v1 = z.motionV1 || z.motion;              // set v2 keeps the original blink timing in motionV1
    pohyb[z.id] = { mrknuti: v1.blinkMs, interval: v1.blinkIntervalMs, radost: v1.happyHoldMs };
    // livelier motion (set v2): per-species tempo and amplitude for the motion curves in static/lib/animals.js
    if (z.motionV2) {
      const { cycle, blink, tilt, hop, sway, breathe, squash } = z.motionV2;
      pohyb[z.id].v2 = { cycle, blink, tilt, hop, sway, breathe, squash, double: !!z.motionV2.double };
    }
  }
  writeFileSync(join(CIL, 'motion.js'), HLAVICKA + `export const POHYB = ${JSON.stringify(pohyb, null, 1)};\n`);
}

/** a set's script that defines `const NAME = {…}` → that object */
function zeSkriptu(soubor, nazev) {
  const ctx = {};
  vm.createContext(ctx);
  vm.runInContext(readFileSync(soubor, 'utf8') + `\n;globalThis.__v = ${nazev};`, ctx);
  return ctx.__v;
}

/**
 * Set V13 (the original V8 drawings in motion): the drawing and its clean plate as WebP for static/lib/natural.js,
 * v13.js with the rig (eyes, mouth, head anchor, paws, soft parts; descriptions and unused fields left out), and the
 * expression atlases from the set's portraits (the same original drawing; happy and wink with the V13 mouth).
 */
function sadaV13(sada, m) {
  const rig = JSON.parse(readFileSync(join(sada, 'rig-data.json'), 'utf8'));
  const parts = zeSkriptu(join(sada, 'reference/reference-parts.js'), 'RUSALKA_PARTS');
  const secondary = zeSkriptu(join(sada, 'reference/reference-secondary.js'), 'RUSALKA_SECONDARY');
  const tmp = join(tmpdir(), 'rusalka-v13');
  rmSync(tmp, { recursive: true, force: true }); mkdirSync(tmp, { recursive: true });
  rmSync(join(CIL, 'v13'), { recursive: true, force: true }); mkdirSync(join(CIL, 'v13'), { recursive: true });
  const webp = (z, kam, q = 90) => execFileSync('cwebp', ['-quiet', '-q', String(q), '-alpha_q', '100', '-exact', z, '-o', kam]);
  const RIG = {}, CASTI = {}, OBLASTI = {};
  for (const z of m.animals) {
    const id = z.id, a = rig[id];
    if (!a || !parts[id] || !secondary[id]) throw new Error(`incomplete rig for ${id}`);
    webp(join(sada, a.source), join(CIL, 'v13', `${id}.webp`));
    webp(join(sada, a.cleanPlate), join(CIL, 'v13', `${id}-oci.webp`), 85);
    RIG[id] = { source: `animals/v13/${id}.webp`, cleanPlate: `animals/v13/${id}-oci.webp`, eyes: a.eyes.map(e => ({ center: e.center, radius: e.radius })), eyeAngle: a.eyeAngle, mouth: a.mouth };
    CASTI[id] = { eyes: parts[id].eyes, headAnchor: parts[id].headAnchor, limbs: parts[id].limbs };
    OBLASTI[id] = { bones: secondary[id].bones.map(({ name, twitch, eventPhase, amount, ...b }) => b) };
    if (secondary[id].motionScale != null) OBLASTI[id].motionScale = secondary[id].motionScale;
    // the CSS picture (small icons, no WebGL): the set's portraits in the usual 2×2 atlas
    const bunky = ['idle', 'blink', 'happy', 'wink'].map(v => {
      const b = join(tmp, `${id}-${v}.png`);
      execFileSync('magick', [join(sada, z.portraits[v]), '-filter', 'Lanczos', '-resize', '288x288', b]);
      return b;
    });
    execFileSync('magick', [bunky[0], bunky[1], '+append', join(tmp, 'a.png')]);
    execFileSync('magick', [bunky[2], bunky[3], '+append', join(tmp, 'b.png')]);
    execFileSync('magick', [join(tmp, 'a.png'), join(tmp, 'b.png'), '-append', join(tmp, `${id}.png`)]);
    execFileSync('cwebp', ['-quiet', '-q', '88', '-alpha_q', '100', '-exact', join(tmp, `${id}.png`), '-o', join(CIL, `${id}.webp`)]);
  }
  rmSync(tmp, { recursive: true, force: true });
  writeFileSync(join(CIL, 'v13.js'), HLAVICKA + `export const RIG = ${JSON.stringify(RIG)};\nexport const CASTI = ${JSON.stringify(CASTI)};\nexport const OBLASTI = ${JSON.stringify(OBLASTI)};\n`);
  return Object.keys(RIG);
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const sada = process.argv[2];
  if (!sada) throw new Error('usage: node tools/animals.mjs <finalni-sada-vN folder>');
  const m = JSON.parse(readFileSync(join(sada, 'manifest.json'), 'utf8'));
  mkdirSync(CIL, { recursive: true });
  if (existsSync(join(sada, 'rig-data.json')) && existsSync(join(sada, 'clean-plates'))) {
    console.log(`static/animals/v13: ${sadaV13(sada, m).join(', ')}`);
  } else {
    atlasy(sada, m);
    console.log(`static/animals: ${m.animals.length} animals`);
  }
}
